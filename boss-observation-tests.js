const fs=require('fs');
const assert=require('assert');
const html=fs.readFileSync('index.html','utf8');
const game=fs.readFileSync('game.js','utf8');
const intro=game.slice(game.indexOf('function createEncounter'),game.indexOf('function createRunDeck'));
const scoring=game.slice(game.indexOf('function resolveScore'),game.indexOf('async function animateScoreResolution'));
for(const removed of ['boss-observation-name','boss-rule-name','boss-event-name','boss-view-rules','active-boss-rule'])assert.ok(!html.includes(removed),`removed boss UI remains: ${removed}`);
for(const removed of ['analyzeBossObservation','selectInterventionEvent','describeEncounterEffect','encounterHas'])assert.ok(!game.includes(removed),`removed boss runtime remains: ${removed}`);
assert.ok(intro.includes('stageIntroTitle')&&intro.includes('stage-intro-target'),'battle entry must render a stage title and target score');
assert.ok(!scoring.includes("phase:'Boss'")&&!scoring.includes('silencedSuit')&&!scoring.includes('disabledPersonaIndex'),'scoring must not apply removed boss effects');
console.log('boss-observation-tests: legacy reveal, observation, rule and intervention paths removed');
