const assert=require('assert'),fs=require('fs');
const html=fs.readFileSync('index.html','utf8'),game=fs.readFileSync('game.js','utf8'),css=fs.readFileSync('battle-persona-card-hierarchy.css','utf8');
assert(html.includes('battle-persona-card-hierarchy.css?v=20260831-horizontal-affixes-v5'),'页面必须加载战斗人格卡横向副属性样式');
assert(html.includes('game.js?v=20260902-growth-refresh-round4-v12'),'页面必须刷新综合界面脚本缓存');
const battleRender=game.slice(game.indexOf("const runtimeReady="),game.indexOf('renderPlayedCards();',game.indexOf("const runtimeReady=")));
assert(!battleRender.includes('主词条')&&!battleRender.includes('persona-entry-trigger'),'战斗人格卡不得展示主词条和旧触发说明组件');
assert(!battleRender.includes('persona-runtime-status'),'战斗人格卡不得展示状态信息');
assert(battleRender.includes('<b>主属性</b>'),'每张战斗人格卡必须保留主属性');
assert(battleRender.includes('class="persona-battle-trigger"')&&battleRender.includes('p.trigger||p.template?.mainEffect?.triggerText'),'每张战斗人格卡必须在主属性上方展示具体触发条件');
assert(!battleRender.includes('触发条件</'),'触发条件不得作为独立标签显示');
assert(game.includes('aria-label="人格副属性"')&&game.includes('副属性${attribute.position}'),'每张战斗人格卡必须明确展示两个副属性槽位且编号不留空格');
assert(game.includes("text:slot.unlocked?(attribute?.effectText||'等待属性配置'):'未解锁'"),'未解锁副属性必须显示真实锁定状态，不能虚构数值');
assert(css.includes('grid-template-columns:minmax(0,1fr)'),'两个副属性必须纵向排列');
assert(css.includes('grid-template-columns:max-content minmax(0,1fr)'),'每个副属性槽位内部必须横向排列名称与状态');
assert(css.includes('align-items:center')&&css.includes('gap:8px'),'副属性名称与状态必须在同一行居中对齐');
assert(css.includes('.persona::after{display:none;content:none}'),'人格卡右下角装饰图标必须移除');
assert(css.includes('width:100%')&&css.includes('height:148px'),'人格卡必须保留侧栏完整宽度并为关键说明留足空间');
assert(css.includes('top:50%')&&css.includes('transform:translateY(-50%)'),'四张人格卡必须在侧栏内垂直居中');
assert(css.includes('clamp(330px,24vw,390px)'),'左侧栏必须为人格触发条件保留可读宽度');
assert(css.includes('font-size:13px')&&css.includes('-webkit-line-clamp:2'),'人格触发条件必须使用较大字号并允许显示两行');
assert(css.includes('font-size:15px'),'人格主属性加成必须作为关键结果放大显示');
assert(css.includes('#100d09b8')&&css.includes('#0807055c'),'人格卡底板必须保持半透明以露出背景');
for(const forbidden of ['boss-rail','battle-stage','.cards','.battle-action-button','.score-preview'])assert(!css.includes(forbidden),`本轮不得修改人格卡之外区域：${forbidden}`);
console.log('battle persona card hierarchy tests passed');
